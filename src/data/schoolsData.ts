/**
 * Compiles schools with up-to-date norm calculations
 */
export function compileSchoolsData(weights = DEFAULT_POLICY_WEIGHTS): SchoolRecord[] {
  return RAW_SAMPLE_SCHOOLS.map((school) => {
    const legislationNorm = calculateLegislationNorm(school.schoolType, school.studentCount, school.isBoarding);
    const weightedModelNorm = calculateWeightedModelNorm(
      school.schoolType,
      school.studentCount,
      school.settlement,
      school.socioeconomicTier,
      weights,
      school.isBoarding
    );

    const deficit = Math.max(0, legislationNorm - school.currentCounselors);
    const weightedDeficit = Math.max(0, weightedModelNorm - school.currentCounselors);
    const studentPerCounselor = school.currentCounselors > 0
      ? Math.round(school.studentCount / school.currentCounselors)
      : school.studentCount;

    const bracketDetail = getNormBracketDetail(school.schoolType, school.studentCount, school.isBoarding);

    return {
      ...school,
      legislationNorm,
      weightedModelNorm,
      deficit,
      weightedDeficit,
      studentPerCounselor,
      isBelowThreshold: bracketDetail.isBelowThreshold,
      currentBracketRange: bracketDetail.currentBracketRange,
      neededForNextNorm: bracketDetail.neededForNextNorm,
    };
  });
}
